const G = (i: number) => GRADIENTS[i % GRADIENTS.length];
const P = (i: number) => POSTERS[i % POSTERS.length];

const dl = (
  link: string,
  fileName: string,
  quality: string,
  isDubbed: boolean,
  season?: number | null,
  episode?: number | null,
): Download => ({
  link,
  fileName,
  quality,
  isDubbed,
  season: season ?? null,
  episode: episode ?? null,
});

function seriesDownloads(base: string, seasons: number, epsPerSeason: number): Download[] {
  const out: Download[] = [];
  for (let s = 1; s <= seasons; s++) {
    for (let e = 1; e <= epsPerSeason; e++) {
      out.push(
        dl(
          `https://dl.example.com/${base}/s${s}e${e}-dub.mkv`,
          `${base} فصل ${toFa(s)} قسمت ${toFa(e)} - دوبله فارسی.mkv`,
          "1080p",
          true,
          s,
          e,
        ),
      );
      out.push(
        dl(
          `https://dl.example.com/${base}/s${s}e${e}-sub.mkv`,
          `${base} فصل ${toFa(s)} قسمت ${toFa(e)} - زیرنویس فارسی.mkv`,
          "1080p",
          false,
          s,
          e,
        ),
      );
    }
  }
  return out;
}

